import java.io.File

import scala.meta._

/** Generates ALL the Scala 2.13 code of the `wasm` platform's WIT glue. Nobody writes 2.13 code by hand.
  *
  * WHY generated 2.13 code exists at all (the two-compiler constraint): mainline Scala 3 has no WIT codegen. A WIT
  * import is lowered at the CALL SITE by the compiler backend and `@WitExport` is compiler-emitted, so every call to an
  * import and every export must be compiled by Scala 2.13 + scala-wasm's compiler plugin. The generated bindings
  * themselves (records, variants, enums) are ordinary Scala and compile under Scala 3 too.
  *
  * The pipeline (see build.sbt for the projects):
  *
  *   1. `witLowered`: wit-bindgen-scala (via `scalaJSWitDirectory`) emits the raw bindings into the SHADOW package
  *      `dapr4swit.lowered` (`scalaJSWitPackage`).
  *   2. `witFacade` ([[facade]]): for every raw file, a "same-name facade" under the ORIGINAL package `dapr4swit`: type
  *      aliases + companion vals for every record/variant/enum/alias, and a plain forwarder for every `@WitImport`
  *      function. So Scala 3 code calls `state_read.get(...)` and matches `state_read.GetError.KeyNotFound` exactly as
  *      wit-bindgen-scala documents. If Scala 3 ever gets a WIT backend, this generator is deleted, the bindings are
  *      generated straight into `dapr4swit`, and the dapr4s code does not change. Each imported interface also becomes
  *      a plain trait (`state_read.StateReadImports`) whose companion object is the live implementation (the
  *      package-object forwarders delegate to it). The Scala 3 wall depends on the traits, which is what makes its
  *      error mapping unit-testable with fakes. Each EXPORTED interface becomes a plain trait too
  *      (`invocation_callback.InvocationCallbackExports`) that the Scala 3 wall implements.
  *   3. `witRootStub` ([[rootStub]]): the link-time contract `dapr4s.internal.witglue.AppRoot`, one member per exported
  *      interface. A `Provided` stub; the Scala 3 wall supplies the real object.
  *   4. `witExports` ([[trampolines]]): one `@WitExport` trampoline per exported function, delegating to `AppRoot`.
  *
  * Inputs: the raw bindings (parsed with scalameta) for the import side, and the resolved WIT world as JSON
  * (`wasm-tools component wit wit --json`) for the export side — wit-bindgen-scala emits only the TYPES of exported
  * interfaces, never their function signatures. Anything the generator does not recognise fails the build.
  *
  * Not covered yet (the generator skips them and says so in the output): WIT resources (`crypto`'s encryptor /
  * decryptor / crypto-output). Their methods are imports too, so a Scala 3 caller would need generated wrapper classes;
  * dapr4s has no crypto wall on `wasm` yet.
  */
object WitGlue {
  val Original = "dapr4swit"
  val Lowered = "dapr4swit.lowered"
  val GluePackage = "dapr4s.internal.witglue"

  private val header =
    "// GENERATED by wasm/project/WitGlue.scala. Do not edit: regenerated on every build.\n"

  // -----------------------------------------------------------------------------------------------
  // Naming, as wit-bindgen-scala does it
  // -----------------------------------------------------------------------------------------------
  def pascal(witName: String): String = witName.split('-').map(_.capitalize).mkString
  def camel(witName: String): String = {
    val p = pascal(witName)
    p.head.toLower + p.tail
  }
  def snake(witName: String): String = witName.replace('-', '_')
  private val scalaKeywords = Set("type", "val", "var", "def", "object", "class", "trait", "this", "match", "new")
  def ident(name: String): String = if (scalaKeywords(name)) s"`$name`" else name

  // -----------------------------------------------------------------------------------------------
  // 2. Facade over the raw bindings (import side + exported interfaces' types)
  // -----------------------------------------------------------------------------------------------

  /** One facade file per raw binding file. `exportTraits` maps a package-object FQN (original package) to the extra
    * source (the `<Iface>Exports` trait) to put into it.
    */
  def facade(rawFiles: Seq[File], rawRoot: File, outDir: File, exportTraits: Map[String, String]): Seq[File] = {
    val loweredDir = new File(rawRoot, Lowered.replace('.', '/'))
    rawFiles.filter(_.getName.endsWith(".scala")).map { raw =>
      val rel = loweredDir.toPath.relativize(raw.toPath).toString
      val out = new File(outDir, s"$Original/$rel")
      sbt.IO.write(out, facadeFile(raw, exportTraits))
      out
    }
  }

  private def lowered(fqn: String): String =
    if (fqn.startsWith(Lowered + ".")) fqn else Lowered + fqn.stripPrefix(Original)

  /** Types are copied from the raw signatures; FQNs into the shadow package are pointed back at the facade. */
  private def facadeType(t: Type): String = t.syntax.replace(Lowered + ".", Original + ".")

  private def facadeFile(raw: File, exportTraits: Map[String, String]): String = {
    val source = dialects.Scala213(sbt.IO.read(raw)).parse[Source].get
    val (pkgName, obj) = source.stats match {
      case List(Pkg(ref, List(o: Pkg.Object))) => (ref.syntax, o)
      case other                               =>
        sys.error(s"WitGlue: unexpected shape of $raw: expected one package object, got ${other.map(_.productPrefix)}")
    }
    val origPkg = Original + pkgName.stripPrefix(Lowered)
    val objName = obj.name.value
    val loweredObj = s"$pkgName.$objName"
    val stats = obj.templ.body.stats

    def annotNames(mods: List[Mod]): List[String] = mods.collect { case Mod.Annot(init) => init.tpe.syntax }
    def isResource(mods: List[Mod]) = annotNames(mods).exists(_.endsWith("WitResourceImport"))
    val resources = stats.collect { case c: Defn.Class if isResource(c.mods) => c.name.value }.toSet

    val out = new StringBuilder
    val skipped = List.newBuilder[String]
    val imports = List.newBuilder[(String, String)] // (signature, argument list)

    stats.foreach {
      case t: Defn.Type =>
        out ++= s"  type ${t.name.value} = $loweredObj.${t.name.value}\n"
      case c: Defn.Class if resources(c.name.value) =>
        skipped += s"resource ${c.name.value}"
      case c: Defn.Class =>
        out ++= s"  type ${c.name.value} = $loweredObj.${c.name.value}\n"
      case t: Defn.Trait =>
        out ++= s"  type ${t.name.value} = $loweredObj.${t.name.value}\n"
      case o: Defn.Object if resources(o.name.value) =>
        () // the resource's constructor/static methods: skipped with the class
      case o: Defn.Object =>
        out ++= s"  val ${o.name.value}: $loweredObj.${o.name.value}.type = $loweredObj.${o.name.value}\n"
      case d: Defn.Def if annotNames(d.mods).exists(_.endsWith("WitImport")) =>
        val params = d.paramClauseGroups.flatMap(_.paramClauses).flatMap(_.values)
        val mentionsResource = (params.flatMap(_.decltpe) ++ d.decltpe).exists { t =>
          t.collect { case Type.Name(n) if resources(n) => n }.nonEmpty
        }
        if (mentionsResource) skipped += s"function ${d.name.value} (uses a resource)"
        else {
          val ps = params.map(p => s"${ident(p.name.value)}: ${facadeType(p.decltpe.get)}").mkString(", ")
          val result = facadeType(d.decltpe.getOrElse(sys.error(s"WitGlue: ${d.name} in $raw has no result type")))
          imports += (s"def ${ident(d.name.value)}($ps): $result" -> params
            .map(p => ident(p.name.value))
            .mkString(", "))
        }
      case other =>
        sys.error(s"WitGlue: unexpected definition in $raw: ${other.productPrefix} ${other.syntax.take(80)}")
    }

    val importList = imports.result()
    val traitName = pascal(objName.replace('_', '-')) + "Imports"
    if (importList.nonEmpty) {
      out ++= "\n  /** The WIT imports of this interface as a plain trait. The companion object is the live implementation\n"
      out ++= "    * (compiled here, by the WIT-aware compiler); Scala 3 code depends on the trait and tests pass fakes.\n"
      out ++= "    */\n"
      out ++= s"  trait $traitName {\n"
      importList.foreach { case (sig, _) => out ++= s"    $sig\n" }
      out ++= "  }\n"
      out ++= s"  object $traitName extends $traitName {\n"
      importList.foreach { case (sig, args) =>
        val name = sig.stripPrefix("def ").takeWhile(_ != '(')
        out ++= s"    override $sig = $loweredObj.$name($args)\n"
      }
      out ++= "  }\n\n"
      importList.foreach { case (sig, args) =>
        val name = sig.stripPrefix("def ").takeWhile(_ != '(')
        out ++= s"  $sig = $traitName.$name($args)\n"
      }
    }
    exportTraits.get(s"$origPkg.$objName").foreach(t => out ++= "\n" ++= t)
    val skippedList = skipped.result()
    val skippedNote =
      if (skippedList.isEmpty) ""
      else
        s"  // Not in the facade (WIT resources are not supported by the generator yet): ${skippedList.mkString(", ")}\n"

    s"""${header}package $origPkg
       |
       |/** Same-name facade over `$loweredObj` (the raw wit-bindgen-scala output). */
       |package object $objName {
       |$skippedNote$out}
       |""".stripMargin
  }

  // -----------------------------------------------------------------------------------------------
  // The resolved WIT world (`wasm-tools component wit <dir> --json`)
  // -----------------------------------------------------------------------------------------------
  final case class Fn(witName: String, params: List[(String, String)], result: Option[String])
  final case class ExportedIface(
      namespace: String,
      pkg: String,
      version: String,
      witName: String,
      functions: List[Fn],
  ) {
    def packageObject: String = s"$Original.exports.${snake(namespace)}.$pkg.${snake(witName)}"
    def traitName: String = pascal(witName) + "Exports"
    def traitFqn: String = s"$packageObject.$traitName"
    def rootMember: String = camel(witName)
    def scope: String =
      s"""scala.scalajs.wit.annotation.WitScope("$namespace", "$pkg", "$witName", "$version")"""
  }

  def exportedInterfaces(witJson: String, world: String): List[ExportedIface] = {
    val j = ujson.read(witJson)
    val interfaces = j("interfaces").arr
    val types = j("types").arr
    val packages = j("packages").arr
    val w = j("worlds").arr.find(_("name").str == world).getOrElse(sys.error(s"WitGlue: no world $world"))
    val exportedIds = w("exports").obj.values.toList.map { e =>
      e.obj.get("interface").map(_("id").num.toInt).getOrElse(sys.error(s"WitGlue: unsupported world export $e"))
    }
    val exportedSet = exportedIds.toSet

    def pkgOf(ifaceId: Int): (String, String, String) = {
      val full = packages(interfaces(ifaceId)("package").num.toInt)("name").str // ns:pkg@version
      val (nsPkg, version) = full.span(_ != '@')
      val (ns, pkg) = nsPkg.span(_ != ':')
      (ns, pkg.drop(1), version.drop(1))
    }

    def tpe(ref: ujson.Value): String = ref match {
      case ujson.Str(p) =>
        p match {
          case "bool"   => "Boolean"
          case "s8"     => "Byte"
          case "s16"    => "Short"
          case "s32"    => "Int"
          case "s64"    => "Long"
          case "u8"     => "scala.scalajs.wit.unsigned.UByte"
          case "u16"    => "scala.scalajs.wit.unsigned.UShort"
          case "u32"    => "scala.scalajs.wit.unsigned.UInt"
          case "u64"    => "scala.scalajs.wit.unsigned.ULong"
          case "f32"    => "Float"
          case "f64"    => "Double"
          case "char"   => "Char"
          case "string" => "String"
          case other    => sys.error(s"WitGlue: unsupported primitive $other")
        }
      case ujson.Num(n) =>
        val t = types(n.toInt)
        (t("name"), t("owner")) match {
          case (ujson.Str(name), owner) if owner.objOpt.exists(_.contains("interface")) =>
            val ifaceId = owner("interface").num.toInt
            val (ns, pkg, _) = pkgOf(ifaceId)
            val prefix = if (exportedSet(ifaceId)) s"$Original.exports" else Original
            s"$prefix.${snake(ns)}.$pkg.${snake(interfaces(ifaceId)("name").str)}.${pascal(name)}"
          case _ =>
            val kind = t("kind").obj
            kind.headOption match {
              case Some(("list", e))   => s"Array[${tpe(e)}]"
              case Some(("option", e)) => s"scala.scalajs.wit.Option[${tpe(e)}]"
              case Some(("result", r)) =>
                def side(v: ujson.Value) = if (v.isNull) "Unit" else tpe(v)
                s"scala.scalajs.wit.Result[${side(r("ok"))}, ${side(r("err"))}]"
              case Some(("tuple", r)) =>
                val ts = r("types").arr.map(tpe)
                s"scala.scalajs.wit.Tuple${ts.size}[${ts.mkString(", ")}]"
              case Some(("type", inner)) => tpe(inner)
              case other                 => sys.error(s"WitGlue: unsupported anonymous WIT type $other")
            }
        }
      case other => sys.error(s"WitGlue: unsupported type reference $other")
    }

    exportedIds.map { id =>
      val i = interfaces(id)
      val (ns, pkg, version) = pkgOf(id)
      val fns = i("functions").obj.values.toList.map { f =>
        if (f("kind").str != "freestanding") sys.error(s"WitGlue: unsupported exported function kind ${f("kind")}")
        Fn(
          f("name").str,
          f("params").arr.toList.map(p => p("name").str -> tpe(p("type"))),
          f.obj.get("result").filterNot(_.isNull).map(tpe),
        )
      }
      ExportedIface(ns, pkg, version, i("name").str, fns)
    }
  }

  private def sig(f: Fn, witNames: Boolean): String = {
    val ps = f.params.map { case (n, t) =>
      val ann = if (witNames) s"""@scala.scalajs.wit.annotation.WitName("$n") """ else ""
      s"$ann${ident(camel(n))}: $t"
    }
    s"def ${ident(camel(f.witName))}(${ps.mkString(", ")}): ${f.result.getOrElse("Unit")}"
  }

  /** The `<Iface>Exports` traits, keyed by the package object they go into. */
  def exportTraits(ifaces: List[ExportedIface]): Map[String, String] =
    ifaces.map { i =>
      val body = i.functions.map(f => s"    ${sig(f, witNames = false)}\n").mkString
      i.packageObject ->
        s"""  /** The functions of the exported interface `${i.witName}`, implemented by the Scala 3 wall and reached
           |    * through the generated `@WitExport` trampolines (`$GluePackage.${i.traitName.stripSuffix("s")}`).
           |    */
           |  trait ${i.traitName} {
           |$body  }
           |""".stripMargin
    }.toMap

  // -----------------------------------------------------------------------------------------------
  // 3. Link-time contract stub
  // -----------------------------------------------------------------------------------------------
  def rootStub(ifaces: List[ExportedIface], outDir: File): Seq[File] = {
    val members = ifaces.map(i => s"  def ${i.rootMember}: ${i.traitFqn} = stub\n").mkString
    val out = new File(outDir, GluePackage.replace('.', '/') + "/AppRoot.scala")
    sbt.IO.write(
      out,
      s"""${header}package $GluePackage
         |
         |/** LINK-TIME CONTRACT STUB, never linked: `witExports` depends on this project as `Provided`.
         |  *
         |  * The generated 2.13 `@WitExport` trampolines must call into Scala 3 code (the wall), but a 2.13 project
         |  * cannot depend on a Scala 3 project. So they reference this fixed FQN, and the Scala 3 side supplies the
         |  * real `object $GluePackage.AppRoot` with the same members (src/wasm/internal/AppRoot.scala). A missing
         |  * one is a LINK error ("Referring to non-existent class $GluePackage.AppRoot$$"), not a runtime surprise.
         |  */
         |object AppRoot {
         |  private def stub: Nothing = throw new UnsupportedOperationException("link-time stub")
         |$members}
         |""".stripMargin,
    )
    Seq(out)
  }

  // -----------------------------------------------------------------------------------------------
  // 4. `@WitExport` trampolines
  // -----------------------------------------------------------------------------------------------
  def trampolines(ifaces: List[ExportedIface], outDir: File): Seq[File] = {
    val objs = ifaces.map { i =>
      val fns = i.functions
        .map { f =>
          val args = f.params.map { case (n, _) => ident(camel(n)) }.mkString(", ")
          s"""  @scala.scalajs.wit.annotation.WitExport(${i.scope}, "${f.witName}")
           |  ${sig(f, witNames = true)} =
           |    AppRoot.${i.rootMember}.${ident(camel(f.witName))}($args)
           |""".stripMargin
        }
        .mkString("\n")
      s"""/** `@WitExport` trampolines of `${i.namespace}:${i.pkg}/${i.witName}@${i.version}`. */
         |object ${i.traitName.stripSuffix("s")} {
         |$fns}
         |""".stripMargin
    }
    val out = new File(outDir, GluePackage.replace('.', '/') + "/Exports.scala")
    sbt.IO.write(out, s"${header}package $GluePackage\n\n${objs.mkString("\n")}")
    Seq(out)
  }
}
